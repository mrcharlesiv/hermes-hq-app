import Foundation
import Testing
@testable import HermesHQNative

/// [botdm] A bot messaging another reads as two bots talking: "To Hermes: …" for the call, Hermes's reply for the
/// runner's note, nothing for a delivery with no reply. Texts as Hermes 0.22 writes them (an Inbox → Hermes DM).
@Suite struct BotDMTests {
    static let roster = [DeliveryMessages.Seat(profile: "default", name: "Hermes", head: nil),
                         DeliveryMessages.Seat(profile: "ivy", name: "Ivy", head: nil)]

    static func note(_ output: String, target: String = "-p default") -> String {
        "[IMPORTANT: Background process proc_d5db68493cd7 completed normally (exit code 0).\n"
            + "Command: /Users/x/.hermes/tools/python3 /Users/x/.hermes/hermes-agent/tools/bot_mode_dm.py --run-delivery "
            + "--author '{\"id\":\"bot:inbox\",\"name\":\"inbox\",\"is_bot\":true}' query-file /tmp/dm-1.txt "
            + "--profile-home /Users/x/.hermes /Users/x/.hermes/hermes-agent/.hermes/bin/hermes \(target)\n"
            + "Output:\n\(output)\n]\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]"
    }

    static func message(_ text: String) -> ChatMessage {
        ChatMessage(id: "u1", role: .user, parts: [.text(text)], timestamp: Date(timeIntervalSince1970: 1_790_000_000), rowId: 7)
    }

    @Test func runnerNoteBecomesTheOtherBotsReply() {
        let raw = Self.note(#"{"reply": "The cleanup is still failing ’ coverage.", "status": "settled", "delivery_id": "35"}"#)
        let out = BotDMs.resolve([Self.message(raw)], roster: Self.roster)
        #expect(out.found)
        #expect(out.messages[0].role == .user)
        #expect(out.messages[0].sender?.name == "Hermes")
        #expect(out.messages[0].parts == [.text("The cleanup is still failing ’ coverage.")])
    }

    @Test func outcomes() {
        #expect(BotDMs.outcome(Self.note(#"{"status": "settled", "delivery_id": "1"}"#)) == .delivered)
        #expect(BotDMs.outcome(Self.note(#"{"error": "No canonical Bot Chat", "reason": "runtime_unavailable"}"#)) == .failed("No canonical Bot Chat"))
        #expect(BotDMs.outcome(Self.note("Reply from @ivy:\nOn it.")) == .replied("On it."))
        // The other bot saying nothing draws nothing (2026-10-29: it drew as "From Home", after Hermes's answer).
        #expect(BotDMs.outcome(Self.note(#"{"reply": "[Notification processed; no additional user-facing response.]", "status": "settled"}"#)) == .delivered)
        #expect(BotDMs.outcome(Self.note(#"{"reply": "[SILENT]", "status": "settled"}"#)) == .delivered)
        #expect(BotDMs.outcome(Self.note("Delivery to @ivy failed: gateway down")) == .failed("gateway down"))
        #expect(BotDMs.outcome(Self.note("No reply from @ivy within 600s. The message may still be delivered")) == .noReply)
        #expect(BotDMs.target(Self.note("{}", target: "-p ivy")) == "ivy")
        #expect(BotDMs.target("Command: /x/bin/hermes -p inbox peer dm spark/researcher\nOutput:\n{}") == "spark/researcher")
    }

    /// From history Hermes marks the note an internal notification; it reaches BotDMs as the live note does (owner,
    /// 2026-10-28: it drew as a "…/python3 …/bot_mode_dm.py" process line).
    @Test func historyNoteIsTheOtherBotsReplyToo() {
        let raw = Self.note(#"{"reply": "Checked the job.", "status": "settled"}"#)
        let rows: [JSONValue] = [["role": "user", "content": .string(raw), "display_kind": "internal_notification", "id": 11, "timestamp": 1]]
        let folded = Hydration.fold(rows, pageSeq: 1).messages
        #expect(folded.count == 1 && folded[0].role == .user)
        let out = BotDMs.resolve(folded, roster: Self.roster)
        #expect(out.found && out.messages[0].sender?.name == "Hermes")
        #expect(out.messages[0].parts == [.text("Checked the job.")])
    }

    /// Hermes now files the note as process_complete, titled "Background Process Finished: /Users/…/bin/pytho...".
    /// It reaches BotDMs too: a delivery Inbox didn't answer draws nothing (owner, 2026-10-28: "Users/alex/.hermes/
    /// tools/python-3.14.9+… · 1 more" under Hermes's reply).
    @Test func processCompleteHistoryNoteReachesBotDMs() throws {
        let unanswered = Self.note(#"{"reply": "⚠️ Processing completed but no response was generated. This may be a transient error — try sending your message again.", "status": "settled", "delivery_id": "3540"}"#,
                                   target: "-p inbox")
        let meta: JSONValue = ["display_text": "Background Process Finished: /Users/x/.hermes/tools/python-3.14.9+202****1021-darwin-arm64/bin/pytho..."]
        let rows: [JSONValue] = [
            ["role": "assistant", "content": "Inbox is checking the run.", "id": 20, "timestamp": 1_790_000_000],
            ["role": "user", "content": .string(unanswered), "display_kind": "process_complete", "display_metadata": meta, "id": 21, "timestamp": 1_790_000_030],
            ["role": "user", "content": .string(unanswered), "display_kind": "process_complete", "display_metadata": meta, "id": 22, "timestamp": 1_790_000_040],
            ["role": "user", "content": "What time?", "id": 23, "timestamp": 1_790_000_060],
        ]
        let folded = Hydration.fold(rows, pageSeq: 1).messages
        let out = BotDMs.resolve(folded, roster: Self.roster)
        #expect(out.found)
        let drawn = ChatRowBuilder.build(.init(messages: TimelineNotes.resolve(out.messages), isRunning: false, botName: "Hermes", expanded: []))
        let dump = drawn.map { "\($0.id) \($0.kind)" }
        #expect(!drawn.contains { if case .backgroundResult = $0.kind { return true } else { return false } }, "\(dump)")
        #expect(!dump.contains { $0.contains("python") || $0.contains("Users/") }, "\(dump)")

        // One that did answer is the other bot's reply.
        let answered = Self.note(#"{"reply": "Run checked; nothing changed.", "status": "settled"}"#, target: "-p ivy")
        let one = Hydration.fold([["role": "user", "content": .string(answered), "display_kind": "process_complete",
                                   "display_metadata": meta, "id": 24, "timestamp": 1]], pageSeq: 1).messages
        let replied = BotDMs.resolve(one, roster: Self.roster).messages
        #expect(replied[0].sender?.name == "Ivy" && replied[0].parts == [.text("Run checked; nothing changed.")])
    }

    /// The bot that was messaged gets "Message from 🤖 hermes (@hermes): …", which history marks an internal
    /// notification too. It draws as Hermes's line with Hermes's face, as live (owner, 2026-10-28: the message glyph).
    @Test func historyMessageFromABotHasItsFace() throws {
        let rows: [JSONValue] = [["role": "user", "content": "Message from 🤖 hermes (@hermes): Please repair the builder.",
                                  "display_kind": "internal_notification", "id": 12, "timestamp": 1_790_000_000]]
        let folded = Hydration.fold(rows, pageSeq: 1).messages
        #expect(folded.count == 1 && folded[0].role == .user)
        let resolved = DeliveryMessages.resolve(folded, roster: Self.roster).messages
        var input = ChatRowBuilder.Input(messages: resolved, isRunning: false, botName: "Inbox", expanded: [])
        input.bots = Self.roster
        let row = try #require(ChatRowBuilder.build(input).first { $0.id.hasSuffix("|dl") })
        guard case .backgroundResult(let b) = row.kind else { Issue.record("expected a delivery line"); return }
        #expect(b.face?.profile == "default" && b.face?.name == "Hermes")
        #expect(b.group?.marks.first == .face(b.face!))
        #expect(b.title.hasPrefix("From Hermes: Please repair"))
    }

    @Test func hermesEmptyTurnPlaceholderIsNoReply() {
        let raw = Self.note(#"{"reply": "\u26a0\ufe0f Processing completed but no response was generated. This may be a transient error \u2014 try sending your message again.", "status": "settled"}"#)
        #expect(BotDMs.outcome(raw) == .delivered)
    }

    @Test func plumbingWithoutAReplyDrawsNothing() {
        let quiet = BotDMs.resolve([Self.message(Self.note(#"{"status": "settled"}"#))], roster: Self.roster).messages[0]
        #expect(quiet.role == .system && quiet.parts == [.text("")])
        let failed = BotDMs.resolve([Self.message(Self.note(#"{"error": "busy"}"#, target: "-p ivy"))], roster: Self.roster).messages[0]
        #expect(failed.parts == [.text("Couldn’t reach Ivy: busy")])
        // Any other background process is left to the timeline notes.
        let other = Self.message("[IMPORTANT: Background process proc_1 completed (exit code 0).\nCommand: npm test\nOutput:\nok]")
        #expect(!BotDMs.resolve([other], roster: Self.roster).found)
    }

    @Test func messageAgentCallDrawsAsToTheBot() {
        let call = ToolCall(id: "c1", name: "message_agent", title: "message_agent",
                            argsText: #"{"target": "hermes", "message": "Scheduled cleanup skipped **Personal**.\nPlease check."}"#,
                            summary: nil, state: .done, durationSeconds: nil)
        let m = ChatMessage(id: "a1", role: .assistant, parts: [.tool(call), .text("I told Hermes.")],
                            timestamp: Date(timeIntervalSince1970: 1_790_000_000), rowId: 8)
        var input = ChatRowBuilder.Input(messages: [m], isRunning: false, botName: "Inbox", expanded: [])
        input.bots = Self.roster
        let rows = ChatRowBuilder.build(input)
        let sent = rows.compactMap { row -> BackgroundResultRow? in
            if case .backgroundResult(let b) = row.kind { return b } else { return nil }
        }
        #expect(sent.count == 1)
        #expect(sent.first?.title == "To Hermes: Scheduled cleanup skipped Personal. Please check.")
        #expect(sent.first?.face?.profile == "default")
        // Centred like the other updates, even inside a reply with words of its own (owner, 2026-10-28).
        #expect(sent.first?.group?.count == 1)
        #expect(sent.first?.group?.marks.first == .face(sent.first!.face!))
        #expect(ToolLines.line("message_agent", args: .object(["target": "ivy"])).text == "Messaging ivy")
    }
}
